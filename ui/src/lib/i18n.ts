export type MessageKey = keyof typeof en;

export const catalogs: Record<Locale, Record<MessageKey, string>> = {
  en,
  ko,
};

export function t(locale: Locale, key: string): string {
  return catalogs[locale]?.[key as MessageKey] ?? catalogs.en[key as MessageKey] ?? key;
}

export function catalogHasParity(): boolean {
  const enKeys = Object.keys(catalogs.en).sort();
  const koKeys = Object.keys(catalogs.ko).sort();
  return enKeys.length === koKeys.length && enKeys.every((key, index) => key === koKeys[index]);
}

